"""
Item 4 follow-up -- full-resolution EmotiBit clock-sync analysis.

Newly available: a timeSyncMap.csv AND a timesyncs.csv (continuous log of
individual NTP-style sync pings, roughly every 5s throughout the WHOLE
session, with round-trip latency per ping) now exist for all 79 valid
sessions, regenerated by the user via the EmotiBit app. This supersedes the
2-point timeSyncMap.csv calibration used earlier (audit_synchronization_
evidence.py's item (a), n=1) with a robust, full-session, per-ping fit.

timesyncs.csv columns: RD, TS_received, TS_sent, AK, RoundTrip
  RD, TS_received, AK : EmotiBit onboard millisecond-counter readings
  TS_sent             : local/reference wall-clock time the ping was sent,
                         format YYYY-MM-DD_HH-MM-SS-microseconds, local
                         (Riyadh, UTC+3)
  RoundTrip           : round-trip latency (ms)

Latency-compensated reference time per ping: TS_sent_unix + RoundTrip/2/1000
(confirmed empirically against timeSyncMap.csv's own TL0/TE0 anchor values).

For every session this:
  1. Fits robust_time_unix = a + b * TS_received_ms via linear regression
     over ALL sync pings, after dropping outlier-latency pings (>3x median
     RoundTrip) that would bias the reference-time estimate.
  2. Reports the fitted drift rate (ppm) and fit quality (max residual).
  3. Compares the fitted absolute-time anchor against the CURRENTLY-RELEASED
     anchor (filename-parsed, whole-second resolution) to quantify exactly
     how much each session's EmotiBit-to-VBOX alignment would shift if the
     release were regenerated with this calibration.
  4. Flags any session where the sync-ping fit itself looks unreliable
     (poor linearity, large gaps, non-monotonic pings) -- evidence of a
     mid-session WiFi/clock issue.

Usage:
    python audit_emotibit_timesync_full.py

Environment variables:
    STAGING_DATA_ROOT   raw per-driver session folders (containing EmotiBit/)
"""
