def find_raw_ts_start(main_csv: Path) -> float | None:
    """
    Reproduces emotibit_sync.py's _load_raw_csv() ts_start logic exactly: the
    device-clock timestamp (ms) of the first row whose tag is valid (has a
    known sample rate) and not in SKIP_TAGS. This is the actual EmotiBitTs_0
    zero-point the release's per-row unix_time = t_start_unix +
    (EmotiBitTs - EmotiBitTs_0)/1000 formula uses -- NOT 0, and NOT any
    particular sync ping's own device-time reading.
    """
    with open(main_csv, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            parts = line.rstrip("\n").split(",")
            if len(parts) < 4:
                continue
            try:
                ts_ms = float(parts[0])
                tag = parts[3].strip()
            except ValueError:
                continue
            if tag in es.SKIP_TAGS or tag not in es.SAMPLE_RATES:
                continue
            return ts_ms
    return None

OUT_DIR = Path(__file__).resolve().parent / "validation_output"
OUT_DIR.mkdir(exist_ok=True)

UTC_OFFSET_HOURS = 3
TS_SENT_RE = re.compile(r"(\d{4})-(\d{2})-(\d{2})_(\d{2})-(\d{2})-(\d{2})-(\d+)")


def load_sessions() -> pd.DataFrame:
    df = pd.read_csv(TRIM_CSV)
    return df[df["status"] == "ok"][["tag", "driver", "session"]]


def find_emotibit_dir(driver: int, session: int) -> Path | None:
    for sname in (f"Session {session}", f"Session_{session}", f"Session{session}", f"Seesion {session}"):
        d = STAGING_DATA_ROOT / f"D{driver}" / sname / "EmotiBit"
        if d.exists():
            return d
    return None


def ts_sent_to_unix(s: str) -> float | None:
    m = TS_SENT_RE.match(s.strip())
    if not m:
        return None
    yr, mo, dy, hh, mi, ss, us = (int(x) for x in m.groups())
    us = int(str(us).ljust(6, "0")[:6])  # normalise to microseconds
    dt = datetime(yr, mo, dy, hh, mi, ss, us, tzinfo=timezone(timedelta(hours=UTC_OFFSET_HOURS)))
    return dt.timestamp()


